/**
Составить программу для решения уравнения f(х) = 0
на отрезке [a, b] с точностью eps методом деления отрезка
пополам. Метод состоит в последовательном приближении
к корню за счёт уменьшения отрезка, на котором находится
корень. Каждое новое приближение х находится как
середина текущего отрезка. Границы текущего отрезка
выбираются из условия противоположности знака f(х) на его границах.
Вычисление корня заканчивается, когда длина отрезка станет меньше eps.
Для проверки программы задать а = 0, b = 2, eps = 10^-4
*/

#include <stdio.h>
#include <math.h>
#include <locale.h>

int main()
{
    setlocale(LC_ALL,"");

    printf("--------------------------------------------------------------------");
    double a,b, fa,fb,x,y,eps,i;

    do {
        printf("\nВведите левую границу отрезка a: ");
        scanf("%lf", &a);scanf("%*[^\n]");
        if (a < -0.3 || a >= 100) {
            printf("\n====================================================================");
            printf("\n____________Ошибка:нарушен диапазон входных данных__________________");
            printf("\n====================================================================\n");
        }
    } while (a < -0.3 || a >= 100);

    do {
        printf("\nВведите правую границу отрезка b: ");
        scanf("%lf", &b);scanf("%*[^\n]");
        if (b <= a || b >= 100) {
            printf("\n====================================================================");
            printf("\n____________Ошибка:нарушен диапазон входных данных__________________");
            printf("\n====================================================================\n");
        }
    } while (b <= a || b >= 100);

    do {
        printf("\nВведите требуемую точность eps: ");
        scanf("%lf", &eps);scanf("%*[^\n]");
        if (eps <= 0 || eps >= 10) {
            printf("\n====================================================================");
            printf("\n____________Ошибка:нарушен диапазон входных данных__________________");
            printf("\n====================================================================\n");
        }
    } while (eps <= 0 || eps >= 10);

    printf("--------------------------------------------------------------------");

    printf("\nВведено границу отрезка [a;b]: [%9.6f;%9.6f]\n", a,b);
    printf("Введено требуемую точность eps: %8.6f \n", eps);

    fa = 1 / (a*pow(a+0.3,0.5)+exp(-a)+1.0/7) - a;
    fb = 1 / (b*pow(b+0.3,0.5)+exp(-b)+1.0/7) - b;
    if (fa*fb >= 0){
        printf("\n==========================================================================================================\n");
        printf("На отрезке [%9.6f; %9.6f] нет гарантии существования корня (знаки функции на концах совпадают)\n",a, b);
        printf("==========================================================================================================\n");
        }
    else {
        printf(" __________________________________________________________________\n");
        printf("| n  |         [a;b]         |     x     |    f(x)    | длина отр. |\n");
        printf(" ----+-----------------------+-----------+------------+------------\n");
        for (int n = 1; n > 0;n++){
            i = b-a;
            x = a + i/2;
            y = 1 / (x*pow(x+0.3,0.5)+exp(-x)+1.0/7) - x;
            printf("| %-2d | [%9.6f;%9.6f] | %9.6f | %10.6f | %10.6f |\n",n,a,b,x,y,i);
            if (fa*y < 0){
                b = x;
            }
            else {
                a = x;
            }
            if (i <= eps){
                n = -1;
            }
    }
    printf(" ==== ======================= =========== ============ ============\n");
    printf("\n====================================================================");
    printf("\nПриближённое значение корня: x = %9.6f.",x);
    printf("\n====================================================================\n");
    }
    return 0;
}
